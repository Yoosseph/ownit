import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import ignore from 'ignore';
import { EMPTY_TREE, git, tryGit } from './git.js';

const DIFF_CHAR_CAP = 60_000;

export interface FileDiff {
  path: string;
  /** `diff --git`, mode, index, rename, and ---/+++ lines. Always sent. */
  header: string;
  /** Hunks. May be truncated. */
  body: string;
  binary: boolean;
}

export interface PreparedDiff {
  diff: string;
  truncated: boolean;
  /** Added plus removed lines in non-ignored files, before truncation. */
  changedLines: number;
  files: number;
  omitted: { path: string; reason: string }[];
}

const LOCKFILES = new Set([
  'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lock', 'bun.lockb',
  'Cargo.lock', 'Gemfile.lock', 'poetry.lock', 'Pipfile.lock', 'uv.lock', 'pdm.lock', 'composer.lock',
  'go.sum', 'flake.lock', 'mix.lock', 'pubspec.lock', 'Podfile.lock', 'packages.lock.json', 'gradle.lockfile',
  'Package.resolved', 'deno.lock',
]);

// Built-in rules, in .gitignore syntax. A .ownitignore at the repo root adds more.
const BUILTIN_IGNORES = [
  'node_modules/', 'dist/', 'build/', 'out/', '.next/', '.nuxt/', 'coverage/', 'vendor/', '__generated__/',
  '*.min.js', '*.min.css', '*.map', '*.bundle.js', '*.chunk.js',
  '*.pb.go', '*_pb2.py', '*_pb2_grpc.py', '*.pb.ts', '*.generated.*', '*.g.dart', '*.freezed.dart',
  '*.snap',
];

const BINARY_EXTENSIONS = /\.(png|jpe?g|gif|webp|ico|bmp|tiff?|psd|pdf|zip|gz|tgz|bz2|xz|7z|rar|jar|war|class|so|dylib|dll|exe|bin|o|a|wasm|woff2?|ttf|otf|eot|mp[34]|mov|avi|webm|wav|ogg|flac|sqlite|db)$/i;
const GENERATED_MARKER = /@generated|DO NOT EDIT|auto-?generated|generated by /i;

function unquote(path: string): string {
  if (!path.startsWith('"')) return path;
  try {
    return JSON.parse(path) as string;
  } catch {
    return path.slice(1, -1);
  }
}

function pathFromHeader(header: string): string {
  const plus = header.match(/^\+\+\+ (?:b\/)?(.+)$/m)?.[1];
  if (plus && plus !== '/dev/null') return unquote(plus);
  const minus = header.match(/^--- (?:a\/)?(.+)$/m)?.[1];
  if (minus && minus !== '/dev/null') return unquote(minus);
  const renamed = header.match(/^rename to (.+)$/m)?.[1];
  if (renamed) return unquote(renamed);
  const first = header.split('\n')[0] ?? '';
  const idx = first.lastIndexOf(' b/');
  return unquote(idx >= 0 ? first.slice(idx + 3) : first.replace(/^diff --git a\//, ''));
}

/** Splits `git diff` output into per-file header and body. */
export function parseDiff(text: string): FileDiff[] {
  const files: FileDiff[] = [];
  const chunks = text.split(/^(?=diff --git )/m).filter((c) => c.startsWith('diff --git '));
  for (const chunk of chunks) {
    const hunkStart = chunk.search(/^@@ /m);
    const header = hunkStart === -1 ? chunk : chunk.slice(0, hunkStart);
    const body = hunkStart === -1 ? '' : chunk.slice(hunkStart);
    files.push({
      path: pathFromHeader(header),
      header: header.endsWith('\n') ? header : `${header}\n`,
      body,
      binary: /^Binary files .* differ$/m.test(header) || /^GIT binary patch$/m.test(header),
    });
  }
  return files;
}

/** Counts added and removed lines inside hunks only. */
export function countChangedLines(body: string): number {
  let count = 0;
  for (const line of body.split('\n')) {
    if ((line.startsWith('+') || line.startsWith('-')) && !line.startsWith('+++ ') && !line.startsWith('--- ')) count++;
  }
  return count;
}

export type IgnoreCheck = (path: string, file?: FileDiff) => string | null;

/** Returns the reason a file is excluded from the debrief, or null to keep it. */
export function ignoreRules(ownitignore = ''): IgnoreCheck {
  const builtin = ignore().add(BUILTIN_IGNORES);
  const custom = ignore().add(ownitignore);
  return (path, file) => {
    const name = path.split('/').pop() ?? path;
    if (LOCKFILES.has(name)) return 'lockfile';
    if (builtin.ignores(path)) return 'generated or build output';
    if (custom.ignores(path)) return '.ownitignore';
    if (file?.binary || BINARY_EXTENSIONS.test(path)) return 'binary';
    if (file) {
      const firstAdded = file.body
        .split('\n')
        .filter((l) => l.startsWith('+'))
        .slice(0, 15)
        .join('\n');
      if (GENERATED_MARKER.test(firstAdded)) return 'generated';
      // Minified: very long added lines.
      if (file.body.split('\n').some((l) => l.length > 2000)) return 'minified';
    }
    return null;
  };
}

/** Cuts text to at most `limit` characters at a line boundary. */
function cutLines(text: string, limit: number): { text: string; droppedLines: number } {
  if (text.length <= limit) return { text, droppedLines: 0 };
  let end = text.lastIndexOf('\n', limit);
  if (end <= 0) end = 0;
  const kept = text.slice(0, end + (end ? 1 : 0));
  const droppedLines = text.slice(kept.length).split('\n').filter(Boolean).length;
  return { text: kept, droppedLines };
}

/**
 * Fits the diff under `cap` characters. Every file header is kept; the body
 * budget is shared fairly, so one huge file cannot crowd out the rest.
 */
export function truncateFiles(files: FileDiff[], cap = DIFF_CHAR_CAP): { text: string; truncated: boolean } {
  const headerChars = files.reduce((sum, f) => sum + f.header.length, 0);
  let remaining = Math.max(0, cap - headerChars);
  const bodies = new Map<FileDiff, string>();
  let truncated = false;
  const bySize = [...files].sort((a, b) => a.body.length - b.body.length);
  bySize.forEach((file, i) => {
    const share = Math.floor(remaining / (bySize.length - i));
    if (file.body.length <= share) {
      bodies.set(file, file.body);
      remaining -= file.body.length;
      return;
    }
    truncated = true;
    const marker = (n: number) => `[ownit: ${n} more lines of this file not shown]\n`;
    const { text, droppedLines } = cutLines(file.body, Math.max(0, share - marker(999999).length));
    const body = `${text}${marker(droppedLines)}`;
    bodies.set(file, body);
    remaining -= body.length;
  });
  return { text: files.map((f) => f.header + (bodies.get(f) ?? '')).join(''), truncated };
}

/** Filters ignored files out of a raw diff, then truncates what is left. */
export function prepareDiff(raw: string, check: IgnoreCheck, cap = DIFF_CHAR_CAP): PreparedDiff {
  const kept: FileDiff[] = [];
  const omitted: PreparedDiff['omitted'] = [];
  for (const file of parseDiff(raw)) {
    const reason = check(file.path, file);
    if (reason) omitted.push({ path: file.path, reason });
    else kept.push(file);
  }
  const changedLines = kept.reduce((sum, f) => sum + countChangedLines(f.body), 0);
  const { text, truncated } = truncateFiles(kept, cap);
  const note = omitted.length
    ? `\n# Not shown (ignored by ownit): ${omitted.map((o) => `${o.path} (${o.reason})`).join(', ')}\n`
    : '';
  return { diff: text + note, truncated, changedLines, files: kept.length, omitted };
}

/** Reads .ownitignore from the pushed commit, falling back to the working tree. */
function readOwnitignore(head: string, cwd = process.cwd()): string {
  const committed = tryGit(['show', `${head}:.ownitignore`], cwd);
  if (committed !== null) return committed;
  const root = tryGit(['rev-parse', '--show-toplevel'], cwd)?.trim();
  try {
    return root ? readFileSync(join(root, '.ownitignore'), 'utf8') : '';
  } catch {
    return '';
  }
}

/** Builds the filtered diff for one or more ranges (a null base means the empty tree). */
export function buildDiff(ranges: { base: string | null; head: string }[], cwd = process.cwd()): PreparedDiff {
  const raw = ranges
    .map(({ base, head }) => git(['diff', '--no-color', '--no-ext-diff', '--find-renames', '--unified=3', base ?? EMPTY_TREE, head], cwd))
    .join('');
  return prepareDiff(raw, ignoreRules(readOwnitignore(ranges[0]!.head, cwd)));
}
