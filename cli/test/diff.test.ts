import { describe, expect, it } from 'vitest';
import { countChangedLines, ignoreRules, parseDiff, prepareDiff, truncateFiles, type FileDiff } from '../src/diff.js';

function fileDiff(path: string, added: string[], extraHeader = ''): string {
  return [
    `diff --git a/${path} b/${path}`,
    'index 1111111..2222222 100644',
    ...(extraHeader ? [extraHeader] : []),
    `--- a/${path}`,
    `+++ b/${path}`,
    `@@ -1,1 +1,${added.length + 1} @@`,
    ' unchanged',
    ...added.map((l) => `+${l}`),
    '',
  ].join('\n');
}

describe('parseDiff', () => {
  it('splits files into header and body', () => {
    const files = parseDiff(fileDiff('src/a.ts', ['x']) + fileDiff('src/b c.ts', ['y', 'z']));
    expect(files.map((f) => f.path)).toEqual(['src/a.ts', 'src/b c.ts']);
    expect(files[0]!.header).toContain('+++ b/src/a.ts');
    expect(files[0]!.body.startsWith('@@')).toBe(true);
  });

  it('handles deleted, binary, and renamed files', () => {
    const raw = [
      'diff --git a/old.ts b/old.ts\ndeleted file mode 100644\nindex 1..0\n--- a/old.ts\n+++ /dev/null\n@@ -1 +0,0 @@\n-gone\n',
      'diff --git a/logo.png b/logo.png\nindex 1..2 100644\nBinary files a/logo.png and b/logo.png differ\n',
      'diff --git a/x.ts b/y.ts\nsimilarity index 100%\nrename from x.ts\nrename to y.ts\n',
    ].join('');
    const files = parseDiff(raw);
    expect(files.map((f) => [f.path, f.binary])).toEqual([
      ['old.ts', false],
      ['logo.png', true],
      ['y.ts', false],
    ]);
  });

  it('counts changed lines inside hunks only', () => {
    const [file] = parseDiff(fileDiff('a.ts', ['one', 'two', '-- not a header']));
    expect(countChangedLines(file!.body)).toBe(3);
  });
});

describe('ignore rules', () => {
  const check = ignoreRules('docs/generated/\n*.csv\n');

  it.each([
    ['package-lock.json', 'lockfile'],
    ['apps/web/pnpm-lock.yaml', 'lockfile'],
    ['go.sum', 'lockfile'],
    ['node_modules/left-pad/index.js', 'generated or build output'],
    ['dist/index.js', 'generated or build output'],
    ['packages/x/build/out.js', 'generated or build output'],
    ['static/app.min.js', 'generated or build output'],
    ['api/user.pb.go', 'generated or build output'],
    ['docs/generated/api.md', '.ownitignore'],
    ['data/report.csv', '.ownitignore'],
    ['assets/logo.png', 'binary'],
  ])('excludes %s (%s)', (path, reason) => {
    expect(check(path)).toBe(reason);
  });

  it('keeps ordinary source files', () => {
    expect(check('src/cart.ts')).toBeNull();
    expect(check('README.md')).toBeNull();
    expect(check('src/builder.ts')).toBeNull();
  });

  it('detects generated markers and minified content', () => {
    const [generated] = parseDiff(fileDiff('src/schema.ts', ['// Code generated by sqlc. DO NOT EDIT.', 'export {}']));
    expect(check(generated!.path, generated)).toBe('generated');
    const [minified] = parseDiff(fileDiff('src/vendor.js', ['x'.repeat(5000)]));
    expect(check(minified!.path, minified)).toBe('minified');
  });
});

describe('prepareDiff', () => {
  it('drops ignored files, counts only kept lines, and lists what was omitted', () => {
    const raw = fileDiff('src/a.ts', ['a', 'b']) + fileDiff('package-lock.json', Array(500).fill('"x": 1'));
    const prepared = prepareDiff(raw, ignoreRules());
    expect(prepared.changedLines).toBe(2);
    expect(prepared.files).toBe(1);
    expect(prepared.diff).not.toContain('"x": 1');
    expect(prepared.diff).toContain('Not shown (ignored by ownit): package-lock.json (lockfile)');
    expect(prepared.truncated).toBe(false);
  });

  it('truncates to the cap, keeps every header, and says so', () => {
    const big = Array.from({ length: 3000 }, (_, i) => `const line${i} = ${i};`);
    const raw = fileDiff('src/big.ts', big) + fileDiff('src/small.ts', ['tiny']) + fileDiff('src/medium.ts', big.slice(0, 400));
    const prepared = prepareDiff(raw, ignoreRules(), 10_000);
    expect(prepared.truncated).toBe(true);
    expect(prepared.diff.length).toBeLessThanOrEqual(10_000);
    for (const path of ['src/big.ts', 'src/small.ts', 'src/medium.ts']) expect(prepared.diff).toContain(`diff --git a/${path} b/${path}`);
    expect(prepared.diff).toContain('+tiny');
    expect(prepared.diff).toMatch(/\[ownit: \d+ more lines of this file not shown\]/);
    expect(prepared.changedLines).toBe(3401);
  });

  it('shares the budget so a huge file cannot starve the others', () => {
    const files: FileDiff[] = [
      { path: 'a', header: 'h\n', body: 'x\n'.repeat(10_000), binary: false },
      { path: 'b', header: 'h\n', body: 'y\n'.repeat(1_000), binary: false },
    ];
    const { text } = truncateFiles(files, 2_000);
    expect(text.split('y').length - 1).toBeGreaterThan(300);
  });
});
